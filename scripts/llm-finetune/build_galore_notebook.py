     "collator  = DataCollatorForSeq2Seq(tok, padding=True, label_pad_token_id=-100)",
     "",
     "args = TrainingArguments(",
     '    output_dir="galore-qwen3b-helios",',
     "    per_device_train_batch_size=1, gradient_accumulation_steps=8,",
     "    num_train_epochs=3, learning_rate=1e-5, warmup_ratio=0.05,",
     '    bf16=True, logging_steps=20, eval_strategy="steps", eval_steps=200,',
     '    lr_scheduler_type="cosine", seed=42, gradient_checkpointing=True,',
     "    # ---- GaLore : full-parameter, gradients projetes low-rank (8-bit) ----",
     '    optim="galore_adamw_8bit",',
     '    optim_target_modules=[r".*attn.*", r".*mlp.*"],',
