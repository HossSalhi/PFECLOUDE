     '    ids = enc["input_ids"]; labels = [-100]*len(ids); start=None',
     "    for i in range(len(ids)-len(resp_ids), -1, -1):",
     "        if ids[i:i+len(resp_ids)] == resp_ids: start = i+len(resp_ids); break",
