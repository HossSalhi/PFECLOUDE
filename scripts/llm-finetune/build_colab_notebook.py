#!/usr/bin/env python3
"""Genere un notebook Colab .ipynb valide pour fine-tuner Qwen2.5-3B (QLoRA soigne + rsLoRA)
sur train.jsonl/val.jsonl, avec template Qwen + masquage de loss + export GGUF pour Ollama."""
import json, os
D=os.path.dirname(os.path.abspath(__file__))

def md(*lines): return {"cell_type":"markdown","metadata":{},"source":[l+"\n" for l in lines]}
def code(*lines): return {"cell_type":"code","metadata":{},"execution_count":None,"outputs":[],"source":[l+"\n" for l in lines]}

cells=[
md("# 🧠 Fine-tuning Qwen2.5-3B — HELIOS (120 types incidents K8s)",
   "",
   "**Tâche** : incident → `DIAGNOSTIC | ACTION=... | EXPLICATION`. QLoRA soigné (rsLoRA, tous modules).",
   "",
   "**Avant de lancer** : `Runtime → Change runtime type → GPU (T4)`, puis **upload** `train.jsonl` et `val.jsonl`",
   "(icône dossier à gauche → Upload)."),

md("## 1. Installation (Unsloth = 2× plus rapide, tient sur T4 gratuit)"),
code("%%capture",
     "!pip install unsloth",
     '!pip install --no-deps "trl<0.9.0" peft accelerate bitsandbytes'),

md("## 2. Charger Qwen2.5-3B-Instruct en 4-bit"),
code("from unsloth import FastLanguageModel",
     "import torch",
     "",
     "MAX_SEQ = 1024   # tes exemples font max ~288 tokens -> large",
     "model, tokenizer = FastLanguageModel.from_pretrained(",
     '    model_name = "unsloth/Qwen2.5-3B-Instruct-bnb-4bit",',
     "    max_seq_length = MAX_SEQ,",
     "    load_in_4bit = True,",
     "    dtype = None,",
     ")"),

md("## 3. Ajouter les adaptateurs QLoRA (soigné : rank 32, tous les modules, rsLoRA)",
   "*(Pour du **QDoRA** — plus proche du full FT — ajoute `use_dora=True`. Si ça erreur sur T4, retire-le.)*"),
code("model = FastLanguageModel.get_peft_model(",
     "    model,",
     "    r = 32,",
     '    target_modules = ["q_proj","k_proj","v_proj","o_proj","gate_proj","up_proj","down_proj"],',
     "    lora_alpha = 32,",
     "    lora_dropout = 0,",
     '    bias = "none",',
     '    use_gradient_checkpointing = "unsloth",',
     "    random_state = 42,",
     "    use_rslora = True,      # rang-stabilise (plus proche du full FT)",
     "    # use_dora = True,      # <- decommente pour QDoRA (encore plus proche du full FT)",
     ")"),

md("## 4. Charger le dataset + appliquer le template Qwen (ChatML)"),
code("from datasets import load_dataset",
     "from unsloth.chat_templates import get_chat_template",
     "",
     'tokenizer = get_chat_template(tokenizer, chat_template="qwen-2.5")',
     "",
     'ds = load_dataset("json", data_files={"train":"train.jsonl","val":"val.jsonl"})',
     "",
     "def fmt(ex):",
     '    ex["text"] = tokenizer.apply_chat_template(ex["messages"], tokenize=False, add_generation_prompt=False)',
     "    return ex",
     "",
     'train_ds = ds["train"].map(fmt)',
     'val_ds   = ds["val"].map(fmt)',
     'print("train:", len(train_ds), "| val:", len(val_ds))',
     'print(train_ds[0]["text"][:400])'),

md("## 5. Entraîneur SFT + **masquage de loss** (apprend SUR la réponse only)"),
code("from trl import SFTTrainer",
     "from transformers import TrainingArguments",
     "from unsloth.chat_templates import train_on_responses_only",
     "",
     "trainer = SFTTrainer(",
     "    model = model, tokenizer = tokenizer,",
     "    train_dataset = train_ds, eval_dataset = val_ds,",
     '    dataset_text_field = "text",',
     "    max_seq_length = MAX_SEQ, packing = False,",
     "    args = TrainingArguments(",
     "        per_device_train_batch_size = 2,",
     "        gradient_accumulation_steps = 4,",
     "        warmup_ratio = 0.05,",
     "        num_train_epochs = 3,",
     "        learning_rate = 2e-4,",
     "        fp16 = not torch.cuda.is_bf16_supported(), bf16 = torch.cuda.is_bf16_supported(),",
     "        logging_steps = 20,",
     '        eval_strategy = "steps", eval_steps = 200,',
     "        optim = \"adamw_8bit\", weight_decay = 0.01,",
     '        lr_scheduler_type = "cosine", seed = 42, output_dir = "outputs",',
     "    ),",
     ")",
     "",
     "# MASQUAGE DE LOSS : n'entraine que sur la reponse de l'assistant",
     "trainer = train_on_responses_only(",
     "    trainer,",
     '    instruction_part = "<|im_start|>user\\n",',
     '    response_part = "<|im_start|>assistant\\n",',
     ")"),

md("## 6. 🚀 Entraîner (~1-2 h sur T4)"),
code("trainer_stats = trainer.train()"),

md("## 7. Tester le modèle (quelques incidents)"),
code("FastLanguageModel.for_inference(model)",
     "tests = [",
     '    "Incident: checkout CrashLoopBackOff right after a new deploy, panic loading config. Decide the remediation action.",',
     '    "Incident: payment-svc OOMKilled, memory grows steadily over hours until it dies. Decide the remediation action.",',
     '    "Incident: etcd lost quorum, cluster read-only. Decide the remediation action.",',
     "]",
     "for t in tests:",
     '    msgs=[{"role":"system","content":"You are the automatic decision engine of a Kubernetes self-healing system. Reason from the symptoms and output: DIAGNOSTIC: <cause> | ACTION=<ACTION_NAME> | EXPLICATION: <how to fix>."},{"role":"user","content":t}]',
     "    inp = tokenizer.apply_chat_template(msgs, tokenize=True, add_generation_prompt=True, return_tensors='pt').to('cuda')",
     "    out = model.generate(input_ids=inp, max_new_tokens=180, temperature=0.3, do_sample=True)",
     '    print(tokenizer.decode(out[0][inp.shape[1]:], skip_special_tokens=True)); print("-"*80)'),

md("## 8. Exporter en **GGUF Q4** (pour Ollama sur .161)"),
code('model.save_pretrained_gguf("qwen3b-helios", tokenizer, quantization_method="q4_k_m")',
     '# -> genere qwen3b-helios/*.gguf . Telecharge-le (clic droit dans le panneau fichiers).'),

md("## 9. Déployer sur .161 (Ollama, CPU)",
   "```bash",
   "# sur .161, apres avoir copie le .gguf :",
   "cat > Modelfile <<'EOF'",
   "FROM ./qwen3b-helios.Q4_K_M.gguf",
   'SYSTEM \"You are the automatic decision engine of a Kubernetes self-healing system. Reason from the symptoms and output: DIAGNOSTIC: <cause> | ACTION=<ACTION_NAME> | EXPLICATION: <how to fix>.\"',
   "PARAMETER temperature 0.3",
   "PARAMETER num_ctx 1024",
   "EOF",
   "ollama create helios-120-3b -f Modelfile",
   "# test :",
   'curl localhost:11434/api/generate -d \'{"model":"helios-120-3b","prompt":"Incident: ... Decide the remediation action.","stream":false}\'',
   "```"),
]

