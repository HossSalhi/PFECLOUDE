import paramiko, sys, time
key = paramiko.Ed25519Key.from_private_key_file("C:/Users/houss/.ssh/id_ed25519")
def out(s): sys.stdout.buffer.write((s+"\n").encode("utf-8","replace")); sys.stdout.flush()
c=paramiko.SSHClient(); c.set_missing_host_key_policy(paramiko.AutoAddPolicy())
c.connect("192.168.148.153",username="kube",pkey=key,timeout=10,allow_agent=False,look_for_keys=False)
def run(cmd,t=140):
    _,o,e=c.exec_command(cmd,timeout=t); return (o.read().decode(errors="replace")+e.read().decode(errors="replace")).strip()

out("[1] Uncordon les 2 workers")
out(run("kubectl uncordon k8s-worker1 k8s-worker2"))
out("[2] Supprimer toutes les NetworkPolicies chaos")
out(run("kubectl delete networkpolicy helios-chaos-network helios-chaos-service helios-chaos-dns -n pfe --ignore-not-found"))
out("[3] Supprimer le HPA podinfo")
out(run("kubectl delete hpa podinfo -n pfe --ignore-not-found"))
out("[4] Restaurer les resources podinfo (baseline chaos : cpu 1200m / mem 128Mi)")
out(run("kubectl set resources deployment podinfo -n pfe --limits=cpu=1200m,memory=128Mi --requests=cpu=20m,memory=32Mi"))
out("[5] Attente du rollout podinfo")
out(run("kubectl rollout status deploy/podinfo -n pfe --timeout=120s"))
time.sleep(8)
out("\n=== etat final ===")
out("noeuds: "+run("kubectl get nodes --no-headers | awk '{print $1,$2}'"))
out("podinfo: "+run("kubectl get deploy podinfo -n pfe --no-headers"))
out("postgres: "+run("kubectl get cluster postgres -n pfe -o jsonpath='ready={.status.readyInstances} primary={.status.currentPrimary}'"))
out("networkpolicies: "+(run("kubectl get networkpolicy -n pfe --no-headers 2>/dev/null | awk '{print $1}'") or "(aucune)"))
c.close()
